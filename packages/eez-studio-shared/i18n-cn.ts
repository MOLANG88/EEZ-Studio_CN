// 翻译函数：精确匹配；处理省略号后缀；未命中原样返回。
export function t(text: string | undefined | null): string {
    if (text === undefined || text === null) {
        return text as unknown as string;
    }
    if (typeof text !== "string") {
        return text;
    }

    const trimmed = text.trim();
    if (CN_DICT[trimmed] !== undefined) {
        return CN_DICT[trimmed];
    }

    // 处理以 ... 结尾的菜单/按钮文本
    if (trimmed.endsWith("...")) {
        const core = trimmed.substring(0, trimmed.length - 3);
        if (CN_DICT[core] !== undefined) {
            return CN_DICT[core] + "...";
        }
    }

    return text;
}

// 判断词典是否包含该词条（供脚本/测试使用）
export function hasTranslation(text: string): boolean {
    return CN_DICT[text.trim()] !== undefined;
}
